/* Процент прохождения темы по урокам */
function topicPercent(s, topicId) {
  const topic = TOPICS.find(t => t.id === topicId);
  if (!topic) return 0;
  const total = topic.lessons.length;
  const done = topic.lessons.filter(l => s.completedLessons.includes(l.id)).length;
  return total ? Math.round((done / total) * 100) : 0;
}
